public class St {
public static void main(String[] args) {
double number1 = 25;
double number2 = 26;
double decimalNumber = 68.5;
System.out.println("First number: " + number1);
System.out.println("Second number: " + number2);
// Finds the larger value
System.out.println("Larger value: " + Math.max(number1, number2));
// Finds the smaller value
System.out.println("Smaller value: " + Math.min(number1, number2));
// Rounds to the nearest whole number
System.out.println("Rounded value: " + Math.round(decimalNumber));
}}